function setLanguage(lang) {
  window.selectedLang = lang;
  updateTexts();
}

function updateTexts() {
  const lang = window.selectedLang || 'es';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = key.split('.').reduce((o, k) => (o ? o[k] : null), dictionary[lang]);
    if (value) el.innerHTML = value;
  });
  // Update hero gallery placeholders if present
  if (window.updateHeroGallery) window.updateHeroGallery();
  window.updateTeamSection();
}

window.updateTeamSection = function() {
    if (window.renderTeamSection) {
        // Mantener el seleccionado actual
        const selected = window.currentTeamSelected || 0;
        window.renderTeamSection(selected);
    }
};

function getURLLang() {
    const params = new URLSearchParams(window.location.search);
    const lang = params.get('lang');
    if (lang === 'es' || lang === 'en' || lang === 'chi' || lang === 'zh') {
        return lang === 'chi' ? 'zh' : lang;
    }
    return null;
}

document.addEventListener('DOMContentLoaded', () => {
    const urlLang = getURLLang();
    window.selectedLang = urlLang || 'es';
    updateTexts();
});
